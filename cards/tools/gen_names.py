"""Regenerates src/names.ts: every card key -> the entity name in all languages of the packages.

ESPHome gives no language-independent entity id (the HA unique_id is "MAC/0/type/<name>"), so the cards find the
hub entities by name. This script takes the current key -> (Polish name, English name) table, finds the matching
substitution in the language files and writes all language variants of the name (without the bus prefix):
  DD  packages/lang/dd_xx.yaml  n_dd_*   "${dd_name_prefix} - X"
  TT  packages/lang/tt_xx.yaml  n_tt_*   "${tt_name_prefix} - X"
  Hub packages/lang/hub_xx.yaml n_hub_*  "${hub_name_prefix} - X"
  FF  components/f1f2_nasa/translations/f1f2_xx.yaml (component entities, prefix + X, FSV via fsv_format) and
      packages/lang/f1f2_xx.yaml n_f1f2_* (template entities)
Usage: python tools/gen_names.py   (run from the cards folder)
"""
import os, re
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
CARDS = os.path.dirname(HERE)
HUB = os.path.dirname(CARDS)
LANGS = ["pl", "en", "cs", "de", "es", "fr", "hu", "it", "nl", "pt", "sk"]
SRC = {
    "DD": os.path.join(HUB, "packages", "lang", "dd_{}.yaml"),
    "TT": os.path.join(HUB, "packages", "lang", "tt_{}.yaml"),
    "Hub": os.path.join(HUB, "packages", "lang", "hub_{}.yaml"),
    "FFpkg": os.path.join(HUB, "packages", "lang", "f1f2_{}.yaml"),
    "FF": os.path.join(HUB, "components", "f1f2_nasa", "translations", "f1f2_{}.yaml"),
}


class Loader(yaml.SafeLoader):
    pass


Loader.add_multi_constructor("!", lambda l, s, n: None)


def load(path):
    if not os.path.exists(path):
        return {}
    return yaml.load(open(path, encoding="utf-8"), Loader=Loader) or {}


def subs(bus, lang):
    """substitution key -> name without the bus prefix"""
    d = load(SRC[bus].format(lang)).get("substitutions", {}) or {}
    return {k: re.sub(r"^\$\{[a-z0-9_]+\}( - )?", "", v) for k, v in d.items() if isinstance(v, str) and k.startswith("n_")}


def ff(lang):
    """component entity key -> name, missing keys from English (like the component)"""
    base, d = load(SRC["FF"].format("en")), load(SRC["FF"].format(lang))
    out = {}
    for src in (base, d):
        for sec, vals in src.items():
            if isinstance(vals, dict) and sec != "fsv":
                for k, v in vals.items():
                    if isinstance(v, str):
                        out[f"{sec}.{k}"] = v
    fmt = d.get("fsv_format") or base.get("fsv_format")
    if fmt:
        for code, nm in {**(base.get("fsv") or {}), **(d.get("fsv") or {})}.items():
            out[f"fsv.{code}"] = fmt.format(code=code, name=nm)
    return out


TABLE = {bus: {l: subs(bus, l) for l in LANGS} for bus in ("DD", "TT", "Hub", "FFpkg")}
TABLE["FF"] = {l: ff(l) for l in LANGS}

path = os.path.join(CARDS, "src", "names.ts")
old = open(path, encoding="utf-8").read()
rows = re.findall(r'^  (\w+): \["([^"]*)", "([^"]*)"\],', old, re.M)
if not rows:  # already generated: the bus and the PL / EN names are the first columns
    rows = [(k, f"Immergas {b} - {pl}", f"Immergas {b} - {en}")
            for k, b, pl, en in re.findall(r'^  (\w+): \["(DD|TT|FF|Hub)", \["([^"]*)", "([^"]*)"', old, re.M)]
out, missing = [], []
for key, pl, en in rows:
    m = re.match(r"^Immergas (DD|TT|FF|Hub) - (.*)$", pl)
    bus, xpl = (m.group(1), m.group(2)) if m else ("Hub", pl)
    xen = re.sub(r"^Immergas (DD|TT|FF|Hub) - ", "", en)
    found = None
    for src in (["FF", "FFpkg"] if bus == "FF" else [bus]):
        cands = [sk for sk, v in TABLE[src]["pl"].items() if v == xpl]
        cands = [sk for sk in cands if TABLE[src]["en"].get(sk) == xen] or cands \
            or [sk for sk, v in TABLE[src]["en"].items() if v == xen]
        if cands:
            found = (src, cands[0])
            break
    names = [xpl, xen]
    if found:
        src, sk = found
        for l in LANGS:
            v = TABLE[src][l].get(sk)
            if v and v not in names:
                names.append(v)
    else:
        missing.append(key)
    out.append((key, bus, names))

esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
body = "\n".join('  {}: ["{}", [{}]],'.format(k, b, ", ".join(f'"{esc(n)}"' for n in ns)) for k, b, ns in out)
ts = f"""// Generated by tools/gen_names.py from the language files of the packages - do not edit by hand.
// key -> [bus, names without the bus prefix: Polish, English, then the other languages].
export const NAMES = {{
{body}
}} as const satisfies Record<string, readonly [string, readonly string[]]>;
// keys found only on the Immergas Dominus integration (see hub.ts)
export type Key = keyof typeof NAMES | "dom_ch_demand" | "dom_dhw_request" | "dom_last_read" | "dom_failed" | "dom_hum_target" | "dom_flow_target"
  | "dom_ch_time_today" | "dom_ch_share" | "dom_dhw_cycles" | "dom_dhw_last_dur" | "dom_dhw_last_rise" | "dom_starts_h" | "dom_starts_today" | "dom_room_dev" | "dom_ttt" | "dom_dd_today" | "dom_dd_month" | "dom_h_per_dd" | "dom_frost" | "dom_offline" | "dom_vac_temp" | "dom_win_below" | "dom_sum_above" | "dom_frost_thr" | "dom_off_min" | "dom_vacation" | "dom_auto_season" | "dom_vac_until" | "dom_r02" | "dom_r03" | "dom_r10" | "dom_r11" | "dom_t02" | "dom_t05" | "dom_i04" | "dom_i10" | "dom_int_ch" | "dom_int_dhw" | "dom_a31" | "dom_p07";
"""
open(path, "w", encoding="utf-8", newline="\n").write(ts)
print(f"{len(out)} keys, {len(missing)} without a language source (PL / EN only): {', '.join(missing)}")
