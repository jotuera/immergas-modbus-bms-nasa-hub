"""Builds src/i18n_data.ts from i18n/<lang>.json (English UI text -> translation).
Checks: every placeholder {n} of the English text appears in the translation; keys no longer used in the code are dropped
(when i18n/_keys.json, the extractor output, exists). Usage: python tools/gen_i18n.py"""
import json, os, re

CARDS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(CARDS, "i18n")
keys = None
if os.path.exists(os.path.join(D, "_keys.json")):
    keys = {x["en"] for x in json.load(open(os.path.join(D, "_keys.json"), encoding="utf-8"))}
out, report = {}, []
for f in sorted(os.listdir(D)):
    m = re.fullmatch(r"([a-z]{2})\.json", f)
    if not m:
        continue
    lang, tr = m.group(1), json.load(open(os.path.join(D, f), encoding="utf-8"))
    bad = [k for k, v in tr.items() if sorted(re.findall(r"\{\d+\}", k)) != sorted(re.findall(r"\{\d+\}", v))]
    for k in bad:
        tr.pop(k)
    if keys is not None:
        miss = len(keys - set(tr))
        tr = {k: v for k, v in tr.items() if k in keys}
    else:
        miss = 0
    out[lang] = dict(sorted(tr.items()))
    report.append(f"{lang}: {len(tr)} texts, {len(bad)} dropped (placeholders), {miss} missing")
ts = "// Generated by tools/gen_i18n.py from i18n/<lang>.json - do not edit by hand.\n" \
     "export const TR: Record<string, Record<string, string>> = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n"
open(os.path.join(CARDS, "src", "i18n_data.ts"), "w", encoding="utf-8", newline="\n").write(ts)
print("\n".join(report))
