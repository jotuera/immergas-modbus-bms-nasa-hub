"""Builds components/immergas_core/fault_texts.h from tools/fault_texts.json.

tools/fault_texts.json is the project's own list of boiler fault descriptions (PDU 2100), written for this project:
[{"code": 1, "en": "...", "pl": "...", "cs": "...", ...}, ..., {"code": "unknown", ...}]. Fault codes and their
meaning are facts; the wording is ours. Edit the JSON, then run: python tools/gen_fault_texts.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
# order = options of the "Fault language" select (a restored index must keep its language: append only)
LANGS = ["en", "it", "pl", "cs", "hu", "de", "fr", "es", "nl", "pt", "sk"]
NONE_TEXT = {"en": "No faults", "it": "Nessuna anomalia", "pl": "Brak błędów", "cs": "Žádné poruchy", "hu": "Nincs hiba",
             "de": "Keine Störungen", "fr": "Aucune anomalie", "es": "Sin anomalías", "nl": "Geen storingen",
             "pt": "Sem anomalias", "sk": "Žiadne poruchy"}
NONE_CODE = {"en": "None", "it": "Nessuna", "pl": "Brak", "cs": "Žádná", "hu": "Nincs", "de": "Keine", "fr": "Aucune",
             "es": "Ninguna", "nl": "Geen", "pt": "Nenhuma", "sk": "Žiadna"}

rows = json.load(open(os.path.join(HERE, "fault_texts.json"), encoding="utf-8"))
faults = [r for r in rows if isinstance(r["code"], int)]
unknown = next(r for r in rows if r["code"] == "unknown")
missing = [(r["code"], l) for r in rows for l in LANGS if not str(r.get(l, "")).strip()]
assert not missing, f"missing texts: {missing[:10]}"
c = lambda s: json.dumps(" ".join(str(s).split()), ensure_ascii=False)

out = ["#pragma once",
       "// Boiler fault texts (PDU 2100) for the \"Boiler fault (description)\" entities of D+/D- and T-/T+.",
       "// GENERATED by tools/gen_fault_texts.py from tools/fault_texts.json (the project's own wording) - do not edit.",
       "// State = \"<fault>: <what it means>. <what to do>.\", at most kMaxState bytes (Home Assistant allows 255).",
       "#include <cstddef>", "#include <cstdint>", "#include <string>", "", "namespace immergas {", "",
       f"static const size_t kFaultLanguages = {len(LANGS)};",
       "static const size_t kMaxState = 250;", "",
       f"static const uint16_t kFaultCodes[{len(faults)}] = {{" + ", ".join(str(r["code"]) for r in faults) + "};", ""]
for lang in LANGS:
    out.append(f"static const char *const kFaults_{lang}[{len(faults) + 1}] = {{  // last = unknown code")
    out += [f"    {c(r[lang])}," for r in faults + [unknown]]
    out.append("};")
out += ["", "static const char *const *const kFaultTables[kFaultLanguages] = {" + ", ".join(f"kFaults_{l}" for l in LANGS) + "};",
        "static const char *const kNoFault[kFaultLanguages] = {" + ", ".join(c(NONE_TEXT[l]) for l in LANGS) + "};",
        "static const char *const kNoFaultCode[kFaultLanguages] = {" + ", ".join(c(NONE_CODE[l]) for l in LANGS) + "};",
        "",
        "// UTF-8 safe: never cut inside a multi-byte character",
        "inline size_t utf8_floor(const std::string &s, size_t n) {",
        "  if (n >= s.size()) return s.size();",
        "  while (n > 0 && (static_cast<unsigned char>(s[n]) & 0xC0) == 0x80) n--;",
        "  return n;",
        "}",
        "",
        "// a text longer than kMaxState is cut at a word boundary and ends with \"...\"",
        "inline std::string fit_state(const std::string &full) {",
        "  if (full.size() <= kMaxState) return full;",
        "  size_t cut = utf8_floor(full, kMaxState - 3);",
        "  size_t space = full.rfind(' ', cut);",
        "  if (space != std::string::npos && space > kMaxState / 2) cut = space;",
        "  return full.substr(0, cut) + \"...\";",
        "}",
        "",
        "// Description of `code` in language `lang` (index of the \"Fault language\" select).",
        "inline std::string fault_description(int code, size_t lang) {",
        "  if (lang >= kFaultLanguages) lang = 0;",
        "  if (code == 0) return kNoFault[lang];",
        "  size_t i = 0;",
        "  while (i < sizeof(kFaultCodes) / sizeof(kFaultCodes[0]) && kFaultCodes[i] != code) i++;",
        "  return fit_state(kFaultTables[lang][i]);  // i == number of codes -> the \"unknown\" text",
        "}",
        "",
        "// \"Boiler fault (code)\" when there is no fault.",
        "inline const char *fault_none_code(size_t lang) { return kNoFaultCode[lang < kFaultLanguages ? lang : 0]; }",
        "", "}  // namespace immergas", ""]
dst = os.path.join(REPO, "components", "immergas_core", "fault_texts.h")
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(f"{len(faults)} codes x {len(LANGS)} languages -> {dst}")
